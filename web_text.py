def text(cfg: Optional[dict]) -> Dict[str, str]:
    """The catalog for `[web] language`, the server's default (a person's own choice replaces it in
    web.py before it gets here); English (logged) when the language is unknown."""
    language = ((cfg or {}).get("web", {}).get("language")) or DEFAULT_LANGUAGE
    if language not in TEXT:
        log.warning("unknown [web] language %r: using %s", language, DEFAULT_LANGUAGE)
        language = DEFAULT_LANGUAGE
    return TEXT[language]
